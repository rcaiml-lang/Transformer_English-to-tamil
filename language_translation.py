import torch
from transformers import AutoTokenizer, AutoModelForSeq2SeqLM

# Select the pretrained Transformer model
model_name = "facebook/nllb-200-distilled-600M"

# Load tokenizer
tokenizer = AutoTokenizer.from_pretrained(model_name)

# Load Transformer model
model = AutoModelForSeq2SeqLM.from_pretrained(model_name)

# Set input language as English
tokenizer.src_lang = "eng_Latn"

print("Transformer model loaded successfully!")
# Function to translate English into Tamil

def translate_text(english_sentence):

    # Convert English sentence into tokens
    inputs = tokenizer(
        english_sentence,
        return_tensors="pt"
    )

    # Generate Tamil translation
    translated_tokens = model.generate(
        **inputs,
        forced_bos_token_id=tokenizer.convert_tokens_to_ids("tam_Taml"),
        max_length=128
    )

    # Convert tokens into readable Tamil text
    tamil_sentence = tokenizer.decode(
        translated_tokens[0],
        skip_special_tokens=True
    )

    return tamil_sentence

english_text = input("Enter an English sentence: ")

# Call translation function
tamil_text = translate_text(english_text)

# Display the results
print("\nEnglish Sentence:")
print(english_text)

print("\nTamil Translation:")
print(tamil_text)





